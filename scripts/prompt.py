    "Set false ONLY for pure compliments, thanks, feedback-only notes, or casual non-blocking feature wishes. "
    "(7) summary: one concise factual sentence (max 20 words) in the standardized training style, for example: "
    "'{Surface} bug reported on {Platform}.', 'Account access or settings issue reported.', "
