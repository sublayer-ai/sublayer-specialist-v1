    "'Critical {Platform} outage affecting payments or auth.', 'Chargeback risk or fraud flag on {ORDER}.', "
    "'Possible account compromise requiring immediate freeze.', 'Low-severity shipping complaint about {ORDER}.', "
    "'General informational request.', 'Non-support escalation requiring routing.', "
    "'Minor authorization hold complaint.'. "
