    "pure compliments/thanks/feedback-only notes. "
    "ALL CAPS ranting alone does NOT imply high or critical urgency — judge by the underlying issue, not tone. "
    "Never assign low when the text describes crashes, freezes, broken features, chargebacks, or account compromise. "
    "(4) customer_email: extract only the customer's email if that exact address appears in the message. "
    "Ignore support@, noreply@, donotreply@, help@, billing@vendor, and other company notification addresses. "
    "If no customer email appears in the text, set customer_email to null — never invent. "
